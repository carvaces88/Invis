/** Stable “random” qty from id so reloads stay consistent. */
function demoQty(id: string, min = 1, max = 14): number {
  let h = 2166136261;
  for (let i = 0; i < id.length; i++) {
    h ^= id.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  const span = max - min + 1;
  const base = min + (h >>> 0) % span;
  // Occasional half-units for kitchen realism
  return (h >>> 8) % 4 === 0 ? base + 0.5 : base;
}

